#!/usr/bin/env bash
# Runs in CI: print the production .env from GitHub environment secrets/variables
# (passed in as environment variables). Unset optional keys are left out so the
# app's defaults apply.
set -euo pipefail

required=(BOT_TOKEN OWNER_ID POSTGRES_PASSWORD DOMAIN)
optional=(
  TIMEZONE
  ANTHROPIC_API_KEY AI_MODEL AI_PLAN_MODEL WHISPER_MODEL
  GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET
  R2_BUCKET R2_ENDPOINT
)

missing=0
for key in "${required[@]}"; do
  if [ -z "${!key:-}" ]; then
    echo "::error::$key is not set in the production environment" >&2
    missing=1
  fi
done
[ "$missing" -eq 0 ] || exit 1

echo "# Generated by CI from GitHub environment 'production' — edit there, not here."
for key in "${required[@]}" "${optional[@]}"; do
  value="${!key:-}"
  [ -n "$value" ] || continue
  # Single quotes keep values literal for docker compose (no $-interpolation).
  case "$value" in
    *"'"* | *$'\n'*)
      echo "::error::$key contains a single quote or a newline" >&2
      exit 1
      ;;
  esac
  printf "%s='%s'\n" "$key" "$value"
done
